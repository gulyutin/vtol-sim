/*
 * Отказы в полёте — по таблице неисправностей РЛЭ (раздел «Особые случаи в полёте»), плюс потеря
 * связи с НСУ: её в таблице нет, но это самый частый особый случай, и у автопилота на него
 * есть своя реакция. Здесь — перечень, описание последствий и порядок действий оператора;
 * сами последствия считает LiveFlight (flight.ts): inject(id).
 */

export type FailureId =
  | 'link'
  | 'gnss'
  | 'airspeed'
  | 'compass'
  | 'radalt'
  | 'aileron'
  | 'elevator'
  | 'tail'
  | 'pusher'
  | 'rotor'
  | 'vtol'
  | 'power'
  | 'autopilot'
  | 'fire'
  | 'boom'
  | 'wing'
  | 'stabilization';

export interface FailureInfo {
  id: FailureId;
  /** Название — как в таблице РЛЭ. */
  title: string;
  /** Что происходит с аппаратом в симуляторе. */
  effect: string;
  /** Порядок действий оператора. */
  rleActions: string[];
}

